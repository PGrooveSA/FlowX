// Writes .env.local from the running local Supabase stack (`supabase status`).
// Server-only keys are written without the VITE_ prefix so Vite never bundles them.
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const raw = execSync('npx supabase status -o json', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
const status = JSON.parse(raw.slice(raw.indexOf('{')));

const existing = existsSync('.env.local') ? readFileSync('.env.local', 'utf8') : '';
const keep = (key) => existing.match(new RegExp(`^${key}=(.*)$`, 'm'))?.[1] ?? '';

const lines = [
  '# Generated by scripts/write-env.mjs for the LOCAL development stack. Do not commit.',
  `VITE_SUPABASE_URL=${status.API_URL}`,
  `VITE_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
  `VITE_APP_URL=http://localhost:5180`,
  '',
  '# Server-side only (scripts/tests). Never expose to the browser.',
  `SUPABASE_URL=${status.API_URL}`,
  `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
  `DEMO_USER_PASSWORD=${keep('DEMO_USER_PASSWORD')}`,
  '',
];
writeFileSync('.env.local', lines.join('\n'));
console.log('Wrote .env.local for', status.API_URL);
